using System;
using System.Collections.Generic;

namespace Gve.Text;

/// <summary>
/// Data context for <see cref="VarGenerator"/>.
/// </summary>
internal class VarGeneratorContext
{
    /// <summary>
    /// Gets the version tag for this context.
    /// </summary>
    public string VersionTag { get; }

    /// <summary>
    /// Gets the operation entries for this context, sorted by their execution
    /// order.
    /// </summary>
    public IList<VarOperationEntry> Entries { get; }

    /// <summary>
    /// Gets or sets the index of the next operation entry to be processed
    /// in <see cref="Entries"/>.
    /// </summary>
    public int EntryIndex { get; set; }

    /// <summary>
    /// Gets the current context for generation operations.
    /// </summary>
    public VarOperationContext OpContext { get; }

    /// <summary>
    /// Gets the generated results. Whenever a new result is generated by
    /// processing all the base entries, it is added to this list.
    /// </summary>
    public IList<CharNodeSet> Results { get; }

    /// <summary>
    /// Initializes a new instance of the <see cref="VarGeneratorContext"/> class.
    /// </summary>
    /// <remarks>This constructor is used when starting a new generation
    /// session for a given version tag.</remarks>
    /// <param name="text">The base text to start from.</param>
    /// <param name="tag">The version tag.</param>
    /// <param name="entries">The sorted base operation entries.</param>
    /// <exception cref="ArgumentNullException">tag or entries</exception>
    public VarGeneratorContext(string text, string tag,
        IList<VarOperationEntry> entries)
    {
        VersionTag = tag ?? throw new ArgumentNullException(nameof(tag));
        Entries = entries ?? throw new ArgumentNullException(nameof(entries));

        OpContext = new VarOperationContext(new CharNodeSet(text));
        Results = new List<CharNodeSet>();
    }

    /// <summary>
    /// Initializes a new instance of the <see cref="VarGeneratorContext"/> class
    /// by copying the specified <paramref name="source"/> context.
    /// </summary>
    /// <remarks>This constructor is used during the generation process.
    /// </remarks>
    /// <param name="source">The source.</param>
    /// <exception cref="ArgumentNullException">source</exception>
    public VarGeneratorContext(VarGeneratorContext source)
    {
        ArgumentNullException.ThrowIfNull(source);

        VersionTag = source.VersionTag;
        Entries = source.Entries;
        EntryIndex = source.EntryIndex;
        OpContext = source.OpContext.Clone();
        Results = source.Results;
    }

    /// <summary>
    /// Converts to string.
    /// </summary>
    /// <returns>
    /// A <see cref="string" /> that represents this instance.
    /// </returns>
    public override string ToString()
    {
        return $"[{VersionTag}] {EntryIndex}/{Entries.Count}: " +
            $"{OpContext} ({Results.Count})";
    }
}
